create or replace function public.r2_admin_extras() returns json
language sql stable security definer set search_path to 'public' as $$
  select case when not public.is_admin() then null else json_build_object(
    'today', (now() at time zone 'Asia/Seoul')::date,
    'week_start', (date_trunc('week', now() at time zone 'Asia/Seoul'))::date,
    'settings', json_build_object(
        'class_goal_words', coalesce((select value from public.app_settings where key = 'r2_class_goal_words'), '10000'),
        'allow_external', (select value from public.app_settings where key = 'allow_external')),
    'roster', coalesce((select json_agg(json_build_object('email', r.email, 'name', r.name, 'grade', r.grade, 'class_no', r.class_no, 'student_no', r.student_no,
        'joined', exists (select 1 from public.profiles p where lower(p.email) = lower(r.email))) order by r.grade, r.class_no, r.student_no) from public.roster r), '[]'::json),
    'students', coalesce((select json_agg(json_build_object('email', p.email, 'show', p.show_on_board,
        'days', coalesce((select json_agg(d order by d) from (select distinct (a.submitted_at at time zone 'Asia/Seoul')::date d from public.r2_quiz_attempts a
                  where a.user_id = p.id and public.medal_of(a.score, a.total) is not null) x), '[]'::json),
        'stamps', coalesce((select json_agg(json_build_object('book_id', m.book_id, 'country', coalesce(st.country, bk.places[1])))
                  from (select book_id from public.r2_quiz_attempts a where a.user_id = p.id group by book_id having public.medal_of(max(score), max(total)) is not null) m
                  join public.r2_books bk on bk.id = m.book_id
                  left join public.r2_stamps st on st.user_id = p.id and st.book_id = m.book_id), '[]'::json),
        'week_tries', (select count(*) from public.r2_quiz_attempts a where a.user_id = p.id and a.submitted_at > now() - interval '7 days')))
      from public.profiles p), '[]'::json)) end;
$$;

create or replace function public.r2_admin_attempts()
returns table(email text, book_id text, score integer, total integer, medal text, attempt_at timestamptz)
language sql security definer set search_path to 'public' as $$
  select p.email::text, a.book_id::text, a.score::int, a.total::int,
         public.medal_of(a.score, a.total)::text, a.submitted_at
  from public.r2_quiz_attempts a
  join public.profiles p on p.id = a.user_id
  where public.is_admin();
$$;

create or replace function public.r2_admin_set_setting(p_key text, p_value text) returns void
language plpgsql security definer set search_path to 'public' as $$
declare k text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  if p_key = 'class_goal_words' then k := 'r2_class_goal_words';
  elsif p_key = 'allow_external' then k := 'allow_external';
  else raise exception 'unknown setting'; end if;
  update public.app_settings set value = p_value where key = k;
  if not found then insert into public.app_settings(key, value) values (k, p_value); end if;
end $$;

