-- ---------- 학생용 함수 ----------
create or replace function public.r2_my_summary() returns json
language sql stable security definer set search_path to 'public' as $$
  with best as (
    select book_id, max(score) s, max(total) t, count(*) n,
      bool_or(hints = 0 and public.medal_of(score, total) is not null) star
    from public.r2_quiz_attempts where user_id = auth.uid() group by book_id),
  m as (select book_id, s, t, n, star, public.medal_of(s, t) medal from best),
  wins as (
    select book_id, (date_trunc('week', submitted_at at time zone 'Asia/Seoul'))::date wk
    from public.r2_quiz_attempts where user_id = auth.uid() and public.medal_of(score, total) is not null),
  ws as (select (date_trunc('week', now() at time zone 'Asia/Seoul'))::date d)
  select json_build_object(
    'books', coalesce((select json_agg(json_build_object('book_id', m.book_id, 'best', m.s, 'total', m.t, 'attempts', m.n, 'medal', m.medal, 'star', m.star,
        'stamp', case when m.medal is not null then coalesce(st.country, bk.places[1]) end))
      from m left join public.r2_books bk on bk.id = m.book_id
             left join public.r2_stamps st on st.user_id = auth.uid() and st.book_id = m.book_id), '[]'::json),
    'gold', (select count(*) from m where medal = 'gold'),
    'silver', (select count(*) from m where medal = 'silver'),
    'bronze', (select count(*) from m where medal = 'bronze'),
    'stars', (select count(*) from m where star),
    'words', coalesce((select sum(bk.word_count) from m join public.r2_books bk on bk.id = m.book_id where m.medal is not null), 0),
    'weeks', coalesce((select json_agg(distinct wk) from wins), '[]'::json),
    'week_start', (select d from ws),
    'week_books', (select count(distinct w.book_id) from wins w, ws where w.wk = ws.d));
$$;

create or replace function public.r2_leaderboard()
returns table(nickname text, gold integer, silver integer, bronze integer, stars integer)
language sql stable security definer set search_path to 'public' as $$
  with best as (
    select a.user_id, a.book_id, max(a.score) s, max(a.total) t,
      bool_or(a.hints = 0 and public.medal_of(a.score, a.total) is not null) star
    from public.r2_quiz_attempts a group by 1, 2),
  med as (select user_id, public.medal_of(s, t) medal, star from best)
  select p.nickname,
    (count(*) filter (where med.medal = 'gold'))::int,
    (count(*) filter (where med.medal = 'silver'))::int,
    (count(*) filter (where med.medal = 'bronze'))::int,
    (count(*) filter (where med.star))::int
  from med join public.profiles p on p.id = med.user_id
  where p.show_on_board and p.role = 'school' and auth.uid() is not null and med.medal is not null
  group by p.id, p.nickname
  order by 2 desc, 3 desc, 4 desc, 5 desc, 1
  limit 10;
$$;

create or replace function public.r2_my_days() returns json
language sql stable security definer set search_path to 'public' as $$
  select json_build_object(
    'today', (now() at time zone 'Asia/Seoul')::date,
    'days', coalesce((select json_agg(d order by d desc) from (
      select distinct (submitted_at at time zone 'Asia/Seoul')::date d
      from public.r2_quiz_attempts
      where user_id = auth.uid() and public.medal_of(score, total) is not null
        and submitted_at > now() - interval '400 days') x), '[]'::json));
$$;

create or replace function public.r2_class_progress() returns json
language sql stable security definer set search_path to 'public' as $$
  with me as (select grade, class_no from public.profiles where id = auth.uid() and role = 'school' and grade is not null),
  mates as (select p.id from public.profiles p, me where p.grade = me.grade and p.class_no = me.class_no),
  best as (select a.user_id, a.book_id, max(a.score) s, max(a.total) t from public.r2_quiz_attempts a
           where a.user_id in (select id from mates) group by 1, 2),
  won as (select user_id, book_id from best where public.medal_of(s, t) is not null),
  stamped as (select coalesce(st.country, bk.places[1]) country from won w
              join public.r2_books bk on bk.id = w.book_id
              left join public.r2_stamps st on st.user_id = w.user_id and st.book_id = w.book_id)
  select case when not exists (select 1 from me) then null else json_build_object(
    'grade', (select grade from me), 'class_no', (select class_no from me),
    'members', greatest((select count(*) from public.roster r, me where r.grade = me.grade and r.class_no = me.class_no), (select count(*) from mates)),
    'active', (select count(distinct user_id) from won),
    'medals', (select count(*) from won),
    'words', coalesce((select sum(bk.word_count) from won w join public.r2_books bk on bk.id = w.book_id), 0),
    'goal', coalesce((select value::int from public.app_settings where key = 'r2_class_goal_words'), 10000),
    'countries', coalesce((select json_agg(json_build_object('country', country, 'count', c))
                           from (select country, count(*) c from stamped where country is not null group by country) x), '[]'::json)) end;
$$;

create or replace function public.r2_quiz_status(p_book_id text) returns json
language sql stable security definer set search_path to 'public' as $$
  select json_build_object('best', max(score), 'total', max(total), 'attempts', count(*),
    'next_allowed_at', max(submitted_at) + interval '10 minutes')
  from public.r2_quiz_attempts where user_id = auth.uid() and book_id = p_book_id;
$$;

create or replace function public.r2_get_quiz(p_book_id text) returns jsonb
language sql security definer set search_path to 'public' as $$
  select coalesce(jsonb_agg(s.x order by random()), '[]'::jsonb) from (
    select jsonb_build_object('no', q.no, 'question', q.question,
      'choices', (select jsonb_agg(c order by random()) from jsonb_array_elements_text(q.choices) c)) as x
    from public.r2_quiz_questions q join public.r2_books b on b.id = q.book_id
    where q.book_id = p_book_id and b.published and public.can_use_quiz()
  ) s;
$$;

create or replace function public.r2_submit_quiz(p_book_id text, p_answers jsonb) returns json
language plpgsql security definer set search_path to 'public' as $$
declare v_total int; v_score int; v_attempt int; v_best int; v_last timestamptz; v_hints int; v_medal text;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if not public.can_use_quiz() then raise exception 'external: 학교 계정으로 로그인한 학생만 퀴즈를 풀 수 있어요'; end if;
  select max(submitted_at) into v_last from public.r2_quiz_attempts where user_id = auth.uid() and book_id = p_book_id;
  if v_last is not null and v_last + interval '10 minutes' > now() then
    raise exception 'cooldown:%', (v_last + interval '10 minutes');
  end if;
  select count(*) into v_total from public.r2_quiz_questions where book_id = p_book_id;
  if v_total = 0 then raise exception 'no quiz'; end if;
  select count(*) into v_score from public.r2_quiz_questions q
    where q.book_id = p_book_id and (p_answers ->> q.no::text) = (q.choices ->> (q.answer - 1));
  select count(distinct para)::int into v_hints from public.r2_hint_events where user_id = auth.uid() and book_id = p_book_id;
  select coalesce(max(attempt_no), 0) + 1 into v_attempt from public.r2_quiz_attempts where user_id = auth.uid() and book_id = p_book_id;
  insert into public.r2_quiz_attempts (user_id, book_id, attempt_no, score, total, answers, hints)
    values (auth.uid(), p_book_id, v_attempt, v_score, v_total, p_answers, v_hints);
  insert into public.r2_reads (user_id, book_id) values (auth.uid(), p_book_id) on conflict do nothing;
  select max(score) into v_best from public.r2_quiz_attempts where user_id = auth.uid() and book_id = p_book_id;
  v_medal := public.medal_of(v_score, v_total);
  return json_build_object('score', v_score, 'total', v_total, 'attempt', v_attempt, 'best', v_best,
    'medal', v_medal, 'best_medal', public.medal_of(v_best, v_total),
    'hints', v_hints, 'star', (v_medal is not null and v_hints = 0));
end $$;

create or replace function public.r2_log_hint(p_book_id text, p_para integer) returns void
language sql security definer set search_path to 'public' as $$
  insert into public.r2_hint_events (user_id, book_id, para)
  select auth.uid(), p_book_id, p_para
  where public.can_use_quiz() and p_para between 0 and 99
    and exists (select 1 from public.r2_books where id = p_book_id);
$$;

create or replace function public.r2_my_hint_count(p_book_id text) returns integer
language sql stable security definer set search_path to 'public' as $$
  select count(distinct para)::int from public.r2_hint_events where user_id = auth.uid() and book_id = p_book_id;
$$;

create or replace function public.r2_set_stamp(p_book_id text, p_country text) returns text
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'auth: 로그인이 필요해요'; end if;
  if not exists (select 1 from public.r2_books where id = p_book_id and p_country = any(places)) then
    raise exception 'invalid: 이 글의 후보 나라가 아니에요';
  end if;
  if not exists (select 1 from public.r2_quiz_attempts where user_id = auth.uid() and book_id = p_book_id
                 and public.medal_of(score, total) is not null) then
    raise exception 'nomedal: 메달을 받은 뒤에 도장을 찍을 수 있어요';
  end if;
  insert into public.r2_stamps (user_id, book_id, country) values (auth.uid(), p_book_id, p_country)
  on conflict (user_id, book_id) do update set country = excluded.country, updated_at = now();
  return p_country;
end $$;

create or replace function public.r2_set_my_level(p_level text) returns void
language plpgsql security definer set search_path to 'public' as $$
begin
  if p_level is not null and p_level not in ('A0','A1','A2','B1','B2','C1') then raise exception 'bad level'; end if;
  update public.profiles set r2_reading_level = p_level where id = auth.uid();
end $$;

create or replace function public.r2_book_hall_of_fame(p_book_id text)
returns table(kind text, period text, nickname text, achieved_at timestamptz, is_me boolean)
language sql stable security definer set search_path to 'public' as $$
  with g as (
    select a.id, a.user_id, a.submitted_at, (a.submitted_at at time zone 'Asia/Seoul') k
    from public.r2_quiz_attempts a join public.profiles p on p.id = a.user_id
    where a.book_id = p_book_id and p.role = 'school'
      and public.medal_of(a.score, a.total) = 'gold'
  ), r as (
    select g.*, to_char(k, 'YYYY') y, to_char(k, 'YYYY-MM') m,
      row_number() over (order by submitted_at, id) re,
      row_number() over (partition by to_char(k, 'YYYY') order by submitted_at, id) ry,
      row_number() over (partition by to_char(k, 'YYYY-MM') order by submitted_at, id) rm
    from g
  ), nowk as (
    select to_char(now() at time zone 'Asia/Seoul', 'YYYY') y, to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM') m
  ), x as (
    select 'ever'::text kind, null::text period, user_id, submitted_at from r where re = 1
    union all select 'year', r.y, user_id, submitted_at from r, nowk where ry = 1 and r.y = nowk.y
    union all select 'month', r.m, user_id, submitted_at from r, nowk where rm = 1 and r.m = nowk.m
  )
  select x.kind, x.period,
         case when p.show_on_board then coalesce(p.nickname, '독서가') else '숨은 독자' end,
         x.submitted_at, x.user_id = auth.uid()
  from x join public.profiles p on p.id = x.user_id
  where auth.uid() is not null;
$$;

create or replace function public.r2_my_hall_of_fame()
returns table(book_id text, kind text, period text, achieved_at timestamptz)
language sql stable security definer set search_path to 'public' as $$
  with g as (
    select a.id, a.book_id, a.user_id, a.submitted_at, (a.submitted_at at time zone 'Asia/Seoul') k
    from public.r2_quiz_attempts a join public.profiles p on p.id = a.user_id
    where p.role = 'school' and public.medal_of(a.score, a.total) = 'gold'
  ), r as (
    select g.*, to_char(k, 'YYYY') y, to_char(k, 'YYYY-MM') m,
      row_number() over (partition by book_id order by submitted_at, id) re,
      row_number() over (partition by book_id, to_char(k, 'YYYY') order by submitted_at, id) ry,
      row_number() over (partition by book_id, to_char(k, 'YYYY-MM') order by submitted_at, id) rm
    from g
  )
  select book_id, 'ever'::text, null::text, submitted_at from r where re = 1 and user_id = auth.uid()
  union all select book_id, 'year', y, submitted_at from r where ry = 1 and user_id = auth.uid()
  union all select book_id, 'month', m, submitted_at from r where rm = 1 and user_id = auth.uid()
  order by 4 desc;
$$;

-- ---------- 교사용 함수 ----------
create or replace function public.r2_admin_overview()
returns table(email text, name text, nickname text, role text, grade integer, class_no integer, student_no integer, completed integer, gold integer, silver integer, bronze integer, stars integer, words integer, attempts integer, last_activity timestamptz)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  with best as (
    select a.user_id, a.book_id, max(a.score) s, max(a.total) t,
      bool_or(a.hints = 0 and public.medal_of(a.score, a.total) is not null) star
    from public.r2_quiz_attempts a group by 1, 2),
  med as (select b.user_id, b.book_id, public.medal_of(b.s, b.t) medal, b.star from best b),
  act as (select a.user_id, count(*)::int cnt, max(a.submitted_at) last_at from public.r2_quiz_attempts a group by 1)
  select p.email, p.name, p.nickname, p.role, p.grade, p.class_no, p.student_no,
    (count(m.medal))::int,
    (count(*) filter (where m.medal = 'gold'))::int,
    (count(*) filter (where m.medal = 'silver'))::int,
    (count(*) filter (where m.medal = 'bronze'))::int,
    (count(*) filter (where m.star))::int,
    (coalesce(sum(bk.word_count) filter (where m.medal is not null), 0))::int,
    coalesce(max(act.cnt), 0),
    max(act.last_at)
  from public.profiles p
  left join med m on m.user_id = p.id
  left join public.r2_books bk on bk.id = m.book_id
  left join act on act.user_id = p.id
  group by p.id
  order by p.grade nulls last, p.class_no nulls last, p.student_no nulls last, p.email;
end $$;

create or replace function public.r2_admin_scores()
returns table(email text, name text, grade integer, class_no integer, student_no integer, book_id text, best integer, total integer, attempts integer, medal text, star boolean, hints integer, last_at timestamptz)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  select p.email, p.name, p.grade, p.class_no, p.student_no, a.book_id,
    max(a.score)::int, max(a.total)::int, count(*)::int,
    public.medal_of(max(a.score)::int, max(a.total)::int),
    bool_or(a.hints = 0 and public.medal_of(a.score, a.total) is not null),
    max(a.hints)::int, max(a.submitted_at)
  from public.r2_quiz_attempts a join public.profiles p on p.id = a.user_id
  group by p.id, a.book_id
  order by p.grade nulls last, p.class_no nulls last, p.student_no nulls last, p.email, a.book_id;
end $$;

create or replace function public.r2_admin_hint_stats()
returns table(book_id text, para integer, students integer, clicks integer)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  select h.book_id, h.para, count(distinct h.user_id)::int, count(*)::int
  from public.r2_hint_events h group by h.book_id, h.para order by h.book_id, h.para;
end $$;

create or replace function public.r2_admin_question_stats()
returns table(book_id text, no integer, question text, attempts integer, correct integer)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  select q.book_id, q.no, q.question, count(a.id)::int,
    (count(a.id) filter (where (a.answers ->> q.no::text) = (q.choices ->> (q.answer - 1))))::int
  from public.r2_quiz_questions q left join public.r2_quiz_attempts a on a.book_id = q.book_id
  group by q.book_id, q.no, q.question
  order by q.book_id, q.no;
end $$;

