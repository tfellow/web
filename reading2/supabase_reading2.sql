-- MY Knowledge Passport (reading2) 서버 설정
-- Supabase → SQL Editor 에 전체를 붙여 넣고 한 번 Run 하세요. 여러 번 실행해도 괜찮아요.
--
-- 기존 MY Reading Passport 의 테이블·함수를 그대로 본떠서 r2_ 이름으로 따로 만들어요.
--   - 따로 쓰는 것: 글 목록, 퀴즈 문항, 응시 기록, 힌트 기록, 여권 도장, 내 레벨(profiles.r2_reading_level), 반 목표 단어 수
--   - 같이 쓰는 것: 로그인(profiles), 닉네임, 학생 명단(roster), 교사(admins), 순위표 공개 설정, 외부 이용자 허용 설정
-- 기존 독서 여권의 테이블과 함수는 하나도 바꾸지 않아요. (profiles 에 r2_reading_level 칸 하나만 더해요.)
-- 메달 기준(medal_of), 퀴즈 이용 가능 여부(can_use_quiz), 교사 확인(is_admin)은 기존 함수를 그대로 불러 써요.

begin;

-- ---------- 테이블 ----------
create table if not exists public.r2_books (
  id text primary key,
  title text not null,
  cefr text,
  lexile text,
  word_count integer,
  published boolean not null default false,
  featured boolean not null default false,
  places text[]
);

create table if not exists public.r2_quiz_questions (
  book_id text not null references public.r2_books(id) on delete cascade,
  no integer not null,
  question text not null,
  choices jsonb not null,
  answer integer not null,           -- choices 안에서 정답의 위치 (1부터)
  primary key (book_id, no)
);

create table if not exists public.r2_quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id text not null references public.r2_books(id) on delete cascade,
  attempt_no integer not null,
  score integer not null,
  total integer not null,
  answers jsonb not null,
  submitted_at timestamptz not null default now(),
  hints integer not null default 0
);
create index if not exists r2_quiz_attempts_user_book on public.r2_quiz_attempts (user_id, book_id);
create index if not exists r2_quiz_attempts_book on public.r2_quiz_attempts (book_id);

create table if not exists public.r2_hint_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id text not null references public.r2_books(id) on delete cascade,
  para integer not null,
  created_at timestamptz not null default now()
);
create index if not exists r2_hint_events_user_book on public.r2_hint_events (user_id, book_id);

create table if not exists public.r2_stamps (
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id text not null references public.r2_books(id) on delete cascade,
  country text not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

create table if not exists public.r2_reads (
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id text not null references public.r2_books(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

alter table public.profiles add column if not exists r2_reading_level text;

-- ---------- 보안(RLS): 기존 독서 여권과 같은 규칙 ----------
alter table public.r2_books enable row level security;
alter table public.r2_quiz_questions enable row level security;
alter table public.r2_quiz_attempts enable row level security;
alter table public.r2_hint_events enable row level security;
alter table public.r2_stamps enable row level security;
alter table public.r2_reads enable row level security;

drop policy if exists r2_books_select on public.r2_books;
create policy r2_books_select on public.r2_books for select to anon, authenticated using (published or public.is_admin());
drop policy if exists r2_books_admin on public.r2_books;
create policy r2_books_admin on public.r2_books for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists r2_questions_admin on public.r2_quiz_questions;
create policy r2_questions_admin on public.r2_quiz_questions for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists r2_attempts_select on public.r2_quiz_attempts;
create policy r2_attempts_select on public.r2_quiz_attempts for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists r2_reads_select on public.r2_reads;
create policy r2_reads_select on public.r2_reads for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists r2_reads_insert on public.r2_reads;
create policy r2_reads_insert on public.r2_reads for insert to authenticated with check (user_id = auth.uid());
