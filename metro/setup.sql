--
-- 기존 독서 여권·지식 여권의 로그인(profiles), 교사(admins, is_admin), 외부 이용자 허용(can_use_quiz)을 그대로 씁니다.
-- 새로 만드는 것은 tm_ 로 시작하는 테이블과 함수뿐이고, 기존 테이블·함수는 하나도 바꾸지 않아요.
-- 본문(tm_units.content)과 퀴즈 정답은 로그인한 학교 이용자(또는 교사가 허용한 외부 이용자)만 받을 수 있어요.

begin;

-- ---------- 테이블 ----------
create table if not exists public.tm_units (
  id text primary key,              -- 예: m1-01 (노선-단원)
  line_id text not null,            -- m1 = 중1 YBM(박)
  unit integer not null,
  title text not null,
  content jsonb not null,           -- 본문·해설·요약·단어장
  published boolean not null default true
);

create table if not exists public.tm_quiz (
  unit_id text not null references public.tm_units(id) on delete cascade,
  no integer not null,
  question text not null,
  choices jsonb not null,
  answer integer not null,          -- choices 안에서 정답 위치 (1부터)
  why text,
  ids jsonb,                        -- 근거 문장 번호
  primary key (unit_id, no)
);

create table if not exists public.tm_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  unit_id text not null references public.tm_units(id) on delete cascade,
  kind text not null check (kind in ('quiz', 'summary')),
  stage integer not null default 0, -- 줄거리: 1 빈칸, 2 순서, 3 50단어, 4 100단어
  score integer not null,
  total integer not null,
  answers jsonb,
  submitted_at timestamptz not null default now()
);
create index if not exists tm_attempts_user_unit on public.tm_attempts (user_id, unit_id);

create table if not exists public.tm_words (
  user_id uuid not null references auth.users(id) on delete cascade,
  unit_id text not null references public.tm_units(id) on delete cascade,
  word text not null,
  box integer not null default 0 check (box between 0 and 5),   -- 0 처음, 5 완전히 외움
  due date not null default current_date,
  wrong integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (user_id, unit_id, word)
);

-- ---------- 보안(RLS) ----------
alter table public.tm_units enable row level security;
alter table public.tm_quiz enable row level security;
alter table public.tm_attempts enable row level security;
alter table public.tm_words enable row level security;
revoke all on public.tm_units, public.tm_quiz, public.tm_attempts, public.tm_words from anon;

drop policy if exists tm_units_admin on public.tm_units;
create policy tm_units_admin on public.tm_units for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists tm_quiz_admin on public.tm_quiz;
create policy tm_quiz_admin on public.tm_quiz for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists tm_attempts_select on public.tm_attempts;
create policy tm_attempts_select on public.tm_attempts for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists tm_words_select on public.tm_words;
create policy tm_words_select on public.tm_words for select to authenticated using (user_id = auth.uid() or public.is_admin());

-- ---------- 학생 함수 ----------
-- 본문: 로그인 + 이용 허용(학교 계정 또는 허용된 외부 이용자)일 때만 돌려줘요
create or replace function public.tm_get_unit(p_id text) returns jsonb
language sql stable security definer set search_path to 'public' as $$
  select u.content from public.tm_units u
  where u.id = p_id and (u.published or public.is_admin())
    and auth.uid() is not null and (public.can_use_quiz() or public.is_admin());
$$;

create or replace function public.tm_get_quiz(p_id text) returns jsonb
language sql security definer set search_path to 'public' as $$
  select coalesce(jsonb_agg(s.x order by s.no), '[]'::jsonb) from (
    select q.no, jsonb_build_object('no', q.no, 'question', q.question,
      'choices', (select jsonb_agg(c order by random()) from jsonb_array_elements_text(q.choices) c)) as x
    from public.tm_quiz q join public.tm_units u on u.id = q.unit_id
    where q.unit_id = p_id and u.published and auth.uid() is not null and (public.can_use_quiz() or public.is_admin())
  ) s;
$$;

-- 채점은 서버에서 해요. 제출한 뒤에 정답과 근거를 돌려줘요.
create or replace function public.tm_submit_quiz(p_id text, p_answers jsonb) returns json
language plpgsql security definer set search_path to 'public' as $$
declare v_total int; v_score int; v_best int; v_review json;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if not (public.can_use_quiz() or public.is_admin()) then raise exception 'external: 학교 계정으로 로그인한 학생만 퀴즈를 풀 수 있어요'; end if;
  select count(*) into v_total from public.tm_quiz where unit_id = p_id;
  if v_total = 0 then raise exception 'no quiz'; end if;
  select count(*) into v_score from public.tm_quiz q
    where q.unit_id = p_id and (p_answers ->> q.no::text) = (q.choices ->> (q.answer - 1));
  insert into public.tm_attempts (user_id, unit_id, kind, score, total, answers) values (auth.uid(), p_id, 'quiz', v_score, v_total, p_answers);
  select max(score) into v_best from public.tm_attempts where user_id = auth.uid() and unit_id = p_id and kind = 'quiz';
  select json_agg(json_build_object('no', q.no, 'answer', q.choices ->> (q.answer - 1), 'why', q.why, 'ids', q.ids,
    'correct', (p_answers ->> q.no::text) = (q.choices ->> (q.answer - 1))) order by q.no)
    into v_review from public.tm_quiz q where q.unit_id = p_id;
  return json_build_object('score', v_score, 'total', v_total, 'best', v_best, 'review', v_review);
end $$;

create or replace function public.tm_save_summary(p_id text, p_stage integer, p_score integer, p_total integer) returns void
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if p_stage not between 1 and 4 or p_total < 1 or p_score < 0 or p_score > p_total then raise exception 'bad value'; end if;
  insert into public.tm_attempts (user_id, unit_id, kind, stage, score, total) values (auth.uid(), p_id, 'summary', p_stage, p_score, p_total);
end $$;

-- 단어 학습(간격 반복): 맞히면 상자가 올라가고 다음 복습 날짜가 늦어져요 (0·1·2·4·7·14일)
create or replace function public.tm_word_result(p_id text, p_word text, p_ok boolean) returns json
language plpgsql security definer set search_path to 'public' as $$
declare v_box int; v_days int[] := array[0, 1, 2, 4, 7, 14];
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  select box into v_box from public.tm_words where user_id = auth.uid() and unit_id = p_id and word = p_word;
  v_box := case when p_ok then least(coalesce(v_box, 0) + 1, 5) else 0 end;
  insert into public.tm_words (user_id, unit_id, word, box, due, wrong, updated_at)
    values (auth.uid(), p_id, p_word, v_box, current_date + v_days[v_box + 1], case when p_ok then 0 else 1 end, now())
  on conflict (user_id, unit_id, word) do update set box = excluded.box, due = excluded.due,
    wrong = public.tm_words.wrong + case when p_ok then 0 else 1 end, updated_at = now();
  return json_build_object('box', v_box, 'due', current_date + v_days[v_box + 1]);
end $$;

create or replace function public.tm_my_words(p_id text) returns json
language sql stable security definer set search_path to 'public' as $$
  select coalesce(json_agg(json_build_object('word', word, 'box', box, 'due', due, 'wrong', wrong)), '[]'::json)
  from public.tm_words where user_id = auth.uid() and unit_id = p_id;
$$;

-- 노선도에 칠할 내 기록: 단원별 퀴즈 최고점, 줄거리 단계, 외운 단어 수, 오늘 복습할 단어 수
create or replace function public.tm_my_progress() returns json
language sql stable security definer set search_path to 'public' as $$
  select coalesce(json_object_agg(u.id, json_build_object(
    'quiz', (select max(score) from public.tm_attempts a where a.user_id = auth.uid() and a.unit_id = u.id and a.kind = 'quiz'),
    'quizTotal', (select max(total) from public.tm_attempts a where a.user_id = auth.uid() and a.unit_id = u.id and a.kind = 'quiz'),
    'stages', (select coalesce(json_agg(distinct a.stage), '[]'::json) from public.tm_attempts a where a.user_id = auth.uid() and a.unit_id = u.id and a.kind = 'summary' and a.score = a.total),
    'mastered', (select count(*) from public.tm_words w where w.user_id = auth.uid() and w.unit_id = u.id and w.box >= 4),
    'due', (select count(*) from public.tm_words w where w.user_id = auth.uid() and w.unit_id = u.id and w.due <= current_date and w.box < 5)
  )), '{}'::json)
  from public.tm_units u where u.published;
$$;

-- ---------- 교사용 함수 ----------
create or replace function public.tm_admin_scores()
returns table(email text, name text, grade integer, class_no integer, student_no integer, unit_id text,
  quiz_best integer, quiz_total integer, quiz_attempts integer, summary_stage integer, mastered integer, last_at timestamptz)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  with k as (
    select a.user_id, a.unit_id from public.tm_attempts a
    union select w.user_id, w.unit_id from public.tm_words w)
  select p.email, p.name, p.grade, p.class_no, p.student_no, k.unit_id,
    (select max(a.score) from public.tm_attempts a where a.user_id = k.user_id and a.unit_id = k.unit_id and a.kind = 'quiz')::int,
    (select max(a.total) from public.tm_attempts a where a.user_id = k.user_id and a.unit_id = k.unit_id and a.kind = 'quiz')::int,
    (select count(*) from public.tm_attempts a where a.user_id = k.user_id and a.unit_id = k.unit_id and a.kind = 'quiz')::int,
    (select max(a.stage) from public.tm_attempts a where a.user_id = k.user_id and a.unit_id = k.unit_id and a.kind = 'summary' and a.score = a.total)::int,
    (select count(*) from public.tm_words w where w.user_id = k.user_id and w.unit_id = k.unit_id and w.box >= 4)::int,
    greatest((select max(a.submitted_at) from public.tm_attempts a where a.user_id = k.user_id and a.unit_id = k.unit_id),
             (select max(w.updated_at) from public.tm_words w where w.user_id = k.user_id and w.unit_id = k.unit_id))
  from k join public.profiles p on p.id = k.user_id
  order by p.grade nulls last, p.class_no nulls last, p.student_no nulls last, p.email, k.unit_id;
end $$;

-- ---------- 실행 권한: 로그인한 사용자만 ----------
do $$
declare f text;
begin
  foreach f in array array[
    'tm_get_unit(text)', 'tm_get_quiz(text)', 'tm_submit_quiz(text, jsonb)', 'tm_save_summary(text, integer, integer, integer)',
    'tm_word_result(text, text, boolean)', 'tm_my_words(text)', 'tm_my_progress()', 'tm_admin_scores()']
  loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;

commit;
