-- MY History Museum 서버 설정
-- Supabase → SQL Editor 에 전체를 붙여 넣고 한 번 Run 하세요. 여러 번 실행해도 괜찮아요.
--
-- 독서 여권·지식 여권·Reading Metro 의 로그인(profiles), 교사(admins, is_admin), 외부 이용자 허용(can_use_quiz)을 그대로 씁니다.
-- 새로 만드는 것은 hm_ 로 시작하는 테이블과 함수뿐이고, 기존 테이블·함수는 하나도 바꾸지 않아요.
-- 교과서 본문(hm_rooms.content)과 퀴즈 정답은 로그인한 학교 이용자(또는 교사가 허용한 외부 이용자)만 받을 수 있어요.

begin;

-- ---------- 테이블 ----------
create table if not exists public.hm_rooms (
  id text primary key,              -- 예: k1-1 (역사② Ⅰ관 1실), w2-3 (역사① Ⅱ관 3실)
  hall_id text not null,            -- k1 = 역사② Ⅰ. 국가의 형성과 발전
  title text not null,
  content jsonb not null,           -- 해설 문단·용어·사료·카드·연표·인과·필기 노트
  published boolean not null default true
);

create table if not exists public.hm_quiz (
  room_id text not null references public.hm_rooms(id) on delete cascade,
  no integer not null,
  question text not null,
  choices jsonb not null,
  answer integer not null,          -- choices 안에서 정답 위치 (1부터)
  why text,
  pid text,                         -- 근거 문단 id
  primary key (room_id, no)
);

create table if not exists public.hm_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  room_id text not null references public.hm_rooms(id) on delete cascade,
  kind text not null check (kind in ('quiz', 'puzzle')),
  stage text not null default '',   -- 퍼즐: order 연표 순서, chain 인과 잇기, pair 나란히 짝
  score integer not null,
  total integer not null,
  answers jsonb,
  submitted_at timestamptz not null default now()
);
create index if not exists hm_attempts_user_room on public.hm_attempts (user_id, room_id);

-- 인물·개념 카드 복습(간격 반복)
create table if not exists public.hm_cards (
  user_id uuid not null references auth.users(id) on delete cascade,
  room_id text not null references public.hm_rooms(id) on delete cascade,
  card text not null,
  box integer not null default 0 check (box between 0 and 5),
  due date not null default current_date,
  wrong integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (user_id, room_id, card)
);

-- 사료 탐구 서술형 답
create table if not exists public.hm_answers (
  user_id uuid not null references auth.users(id) on delete cascade,
  room_id text not null references public.hm_rooms(id) on delete cascade,
  source_id text not null,
  q_no integer not null,
  answer text not null check (char_length(answer) <= 1000),
  updated_at timestamptz not null default now(),
  primary key (user_id, room_id, source_id, q_no)
);

-- ---------- 보안(RLS) ----------
alter table public.hm_rooms enable row level security;
alter table public.hm_quiz enable row level security;
alter table public.hm_attempts enable row level security;
alter table public.hm_cards enable row level security;
alter table public.hm_answers enable row level security;
revoke all on public.hm_rooms, public.hm_quiz, public.hm_attempts, public.hm_cards, public.hm_answers from anon;

drop policy if exists hm_rooms_admin on public.hm_rooms;
create policy hm_rooms_admin on public.hm_rooms for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists hm_quiz_admin on public.hm_quiz;
create policy hm_quiz_admin on public.hm_quiz for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists hm_attempts_select on public.hm_attempts;
create policy hm_attempts_select on public.hm_attempts for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists hm_cards_select on public.hm_cards;
create policy hm_cards_select on public.hm_cards for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists hm_answers_select on public.hm_answers;
create policy hm_answers_select on public.hm_answers for select to authenticated using (user_id = auth.uid() or public.is_admin());

-- ---------- 학생 함수 ----------
create or replace function public.hm_get_room(p_id text) returns jsonb
language sql stable security definer set search_path to 'public' as $$
  select r.content from public.hm_rooms r
  where r.id = p_id and (r.published or public.is_admin())
    and auth.uid() is not null and (public.can_use_quiz() or public.is_admin());
$$;

create or replace function public.hm_get_quiz(p_id text) returns jsonb
language sql security definer set search_path to 'public' as $$
  select coalesce(jsonb_agg(s.x order by s.no), '[]'::jsonb) from (
    select q.no, jsonb_build_object('no', q.no, 'question', q.question, 'choices', q.choices) as x
    from public.hm_quiz q join public.hm_rooms r on r.id = q.room_id
    where q.room_id = p_id and r.published and auth.uid() is not null and (public.can_use_quiz() or public.is_admin())
  ) s;
$$;

-- 채점은 서버에서 해요. 제출한 뒤에 정답과 근거를 돌려줘요.
create or replace function public.hm_submit_quiz(p_id text, p_answers jsonb) returns json
language plpgsql security definer set search_path to 'public' as $$
declare v_total int; v_score int; v_best int; v_review json;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if not (public.can_use_quiz() or public.is_admin()) then raise exception 'external: 학교 계정으로 로그인한 학생만 퀴즈를 풀 수 있어요'; end if;
  select count(*) into v_total from public.hm_quiz where room_id = p_id;
  if v_total = 0 then raise exception 'no quiz'; end if;
  select count(*) into v_score from public.hm_quiz q
    where q.room_id = p_id and (p_answers ->> q.no::text) = (q.choices ->> (q.answer - 1));
  insert into public.hm_attempts (user_id, room_id, kind, score, total, answers) values (auth.uid(), p_id, 'quiz', v_score, v_total, p_answers);
  select max(score) into v_best from public.hm_attempts where user_id = auth.uid() and room_id = p_id and kind = 'quiz';
  select json_agg(json_build_object('no', q.no, 'answer', q.choices ->> (q.answer - 1), 'why', q.why, 'pid', q.pid,
    'correct', (p_answers ->> q.no::text) = (q.choices ->> (q.answer - 1))) order by q.no)
    into v_review from public.hm_quiz q where q.room_id = p_id;
  return json_build_object('score', v_score, 'total', v_total, 'best', v_best, 'review', v_review);
end $$;

create or replace function public.hm_save_puzzle(p_id text, p_stage text, p_score integer, p_total integer) returns void
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if p_stage not in ('order', 'chain', 'pair') or p_total < 1 or p_score < 0 or p_score > p_total then raise exception 'bad value'; end if;
  insert into public.hm_attempts (user_id, room_id, kind, stage, score, total) values (auth.uid(), p_id, 'puzzle', p_stage, p_score, p_total);
end $$;

-- 카드 복습(간격 반복): 맞히면 상자가 올라가고 다음 복습 날짜가 늦어져요 (0·1·2·4·7·14일)
create or replace function public.hm_card_result(p_id text, p_card text, p_ok boolean) returns json
language plpgsql security definer set search_path to 'public' as $$
declare v_box int; v_days int[] := array[0, 1, 2, 4, 7, 14];
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if char_length(p_card) > 80 then raise exception 'bad value'; end if;
  select box into v_box from public.hm_cards where user_id = auth.uid() and room_id = p_id and card = p_card;
  v_box := case when p_ok then least(coalesce(v_box, 0) + 1, 5) else 0 end;
  insert into public.hm_cards (user_id, room_id, card, box, due, wrong, updated_at)
    values (auth.uid(), p_id, p_card, v_box, current_date + v_days[v_box + 1], case when p_ok then 0 else 1 end, now())
  on conflict (user_id, room_id, card) do update set box = excluded.box, due = excluded.due,
    wrong = public.hm_cards.wrong + case when p_ok then 0 else 1 end, updated_at = now();
  return json_build_object('box', v_box, 'due', current_date + v_days[v_box + 1]);
end $$;

create or replace function public.hm_my_cards(p_id text) returns json
language sql stable security definer set search_path to 'public' as $$
  select coalesce(json_agg(json_build_object('card', card, 'box', box, 'due', due, 'wrong', wrong)), '[]'::json)
  from public.hm_cards where user_id = auth.uid() and room_id = p_id;
$$;

-- 사료 탐구 답 저장 (같은 문항은 고쳐 쓰면 덮어써요)
create or replace function public.hm_save_answer(p_id text, p_source text, p_no integer, p_text text) returns void
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if not (public.can_use_quiz() or public.is_admin()) then raise exception 'external: 학교 계정으로 로그인한 학생만 답을 낼 수 있어요'; end if;
  if char_length(coalesce(p_text, '')) not between 1 and 1000 or char_length(p_source) > 20 then raise exception 'bad value'; end if;
  insert into public.hm_answers (user_id, room_id, source_id, q_no, answer, updated_at) values (auth.uid(), p_id, p_source, p_no, p_text, now())
  on conflict (user_id, room_id, source_id, q_no) do update set answer = excluded.answer, updated_at = now();
end $$;

create or replace function public.hm_my_answers(p_id text) returns json
language sql stable security definer set search_path to 'public' as $$
  select coalesce(json_agg(json_build_object('source', source_id, 'no', q_no, 'answer', answer)), '[]'::json)
  from public.hm_answers where user_id = auth.uid() and room_id = p_id;
$$;

-- 로비 연표에 칠할 내 기록: 전시실별 퀴즈 최고점, 다 푼 퍼즐, 낸 답 수, 외운 카드 수, 오늘 복습할 카드 수
create or replace function public.hm_my_progress() returns json
language sql stable security definer set search_path to 'public' as $$
  select coalesce(json_object_agg(r.id, json_build_object(
    'quiz', (select max(score) from public.hm_attempts a where a.user_id = auth.uid() and a.room_id = r.id and a.kind = 'quiz'),
    'quizTotal', (select max(total) from public.hm_attempts a where a.user_id = auth.uid() and a.room_id = r.id and a.kind = 'quiz'),
    'puzzles', (select coalesce(json_agg(distinct a.stage), '[]'::json) from public.hm_attempts a where a.user_id = auth.uid() and a.room_id = r.id and a.kind = 'puzzle' and a.score = a.total),
    'answers', (select count(*) from public.hm_answers x where x.user_id = auth.uid() and x.room_id = r.id),
    'mastered', (select count(*) from public.hm_cards c where c.user_id = auth.uid() and c.room_id = r.id and c.box >= 4),
    'due', (select count(*) from public.hm_cards c where c.user_id = auth.uid() and c.room_id = r.id and c.due <= current_date and c.box < 5)
  )), '{}'::json)
  from public.hm_rooms r where r.published;
$$;

-- ---------- 교사용 함수 ----------
create or replace function public.hm_admin_scores()
returns table(email text, name text, grade integer, class_no integer, student_no integer, room_id text,
  quiz_best integer, quiz_total integer, quiz_attempts integer, puzzles integer, answers integer, mastered integer, last_at timestamptz)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  with k as (
    select a.user_id, a.room_id from public.hm_attempts a
    union select c.user_id, c.room_id from public.hm_cards c
    union select x.user_id, x.room_id from public.hm_answers x)
  select p.email, p.name, p.grade, p.class_no, p.student_no, k.room_id,
    (select max(a.score) from public.hm_attempts a where a.user_id = k.user_id and a.room_id = k.room_id and a.kind = 'quiz')::int,
    (select max(a.total) from public.hm_attempts a where a.user_id = k.user_id and a.room_id = k.room_id and a.kind = 'quiz')::int,
    (select count(*) from public.hm_attempts a where a.user_id = k.user_id and a.room_id = k.room_id and a.kind = 'quiz')::int,
    (select count(distinct a.stage) from public.hm_attempts a where a.user_id = k.user_id and a.room_id = k.room_id and a.kind = 'puzzle' and a.score = a.total)::int,
    (select count(*) from public.hm_answers x where x.user_id = k.user_id and x.room_id = k.room_id)::int,
    (select count(*) from public.hm_cards c where c.user_id = k.user_id and c.room_id = k.room_id and c.box >= 4)::int,
    greatest((select max(a.submitted_at) from public.hm_attempts a where a.user_id = k.user_id and a.room_id = k.room_id),
             (select max(c.updated_at) from public.hm_cards c where c.user_id = k.user_id and c.room_id = k.room_id),
             (select max(x.updated_at) from public.hm_answers x where x.user_id = k.user_id and x.room_id = k.room_id))
  from k join public.profiles p on p.id = k.user_id
  order by p.grade nulls last, p.class_no nulls last, p.student_no nulls last, p.email, k.room_id;
end $$;

create or replace function public.hm_admin_answers(p_id text)
returns table(email text, name text, grade integer, class_no integer, student_no integer, source_id text, q_no integer, answer text, updated_at timestamptz)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  return query
  select p.email, p.name, p.grade, p.class_no, p.student_no, x.source_id, x.q_no, x.answer, x.updated_at
  from public.hm_answers x join public.profiles p on p.id = x.user_id
  where x.room_id = p_id
  order by x.source_id, x.q_no, p.grade nulls last, p.class_no nulls last, p.student_no nulls last, p.email;
end $$;

-- ---------- 실행 권한: 로그인한 사용자만 ----------
do $$
declare f text;
begin
  foreach f in array array[
    'hm_get_room(text)', 'hm_get_quiz(text)', 'hm_submit_quiz(text, jsonb)', 'hm_save_puzzle(text, text, integer, integer)',
    'hm_card_result(text, text, boolean)', 'hm_my_cards(text)', 'hm_save_answer(text, text, integer, text)', 'hm_my_answers(text)',
    'hm_my_progress()', 'hm_admin_scores()', 'hm_admin_answers(text)']
  loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;

commit;
